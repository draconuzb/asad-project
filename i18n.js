/**
 * Get translated message
 * @param {string} lang - 'uz' or 'ru'
 * @param {string} key - message key
 * @param {object} vars - optional variables to interpolate
 */
function t(lang, key, vars = {}) {
    const dict = messages[lang] || messages['uz'];
    let msg = dict[key] || messages['uz'][key] || key;
    for (const [k, v] of Object.entries(vars)) {
        msg = msg.replace(new RegExp(`{${k}}`, 'g'), v ?? '');
    }
    return msg;
}

/**
 * Get user language from context
 */
function getLang(ctx) {
    return (ctx.state.user && ctx.state.user.lang) || 'uz';
}

